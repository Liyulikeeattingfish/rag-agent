# =============================================================================
# migrate-secrets.ps1
#
# One-shot migration: move plaintext api-keys out of application.yml.
#
#   before:  application.yml        ->  deepseek.api-key: sk-xxxxxx     (COMMITTED!)
#   after:   application.yml        ->  deepseek.api-key: ${DEEPSEEK_API_KEY:}
#            application-local.yml  ->  deepseek.api-key: sk-xxxxxx     (git-ignored)
#
# Safety properties:
#   * never prints key contents
#   * backs up application.yml into %TEMP% (outside the repo), never into the repo
#   * if no key is found, nothing is written at all
#   * reads/writes UTF-8 explicitly, so CJK comments survive
#
# Usage (from anywhere):
#   powershell -ExecutionPolicy Bypass -File .\migrate-secrets.ps1
#
# This script contains no secrets itself, but you may delete it once done.
# =============================================================================

$ErrorActionPreference = 'Stop'

$root      = Split-Path -Parent $MyInvocation.MyCommand.Path
$ymlPath   = Join-Path $root 'src\main\resources\application.yml'
$localPath = Join-Path $root 'src\main\resources\application-local.yml'

if (-not (Test-Path -LiteralPath $ymlPath)) {
    Write-Host "ERROR: file not found -> $ymlPath" -ForegroundColor Red
    exit 1
}

# top-level yaml block name -> environment variable name
$blockEnv = @{
    'deepseek'    = 'DEEPSEEK_API_KEY'
    'siliconflow' = 'SILICONFLOW_API_KEY'
}

$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
$lines     = [System.IO.File]::ReadAllLines($ymlPath, [System.Text.Encoding]::UTF8)

$currentBlock = ''
$keyOf        = @{}   # env var name -> raw key
$blockOf      = @{}   # env var name -> yaml block name
$out          = New-Object 'System.Collections.Generic.List[string]'

foreach ($line in $lines) {
    # remember the most recent top-level block ("deepseek:", "siliconflow:", ...)
    if ($line -match '^([A-Za-z0-9_\-]+):\s*(#.*)?$') {
        $currentBlock = $Matches[1]
        $out.Add($line)
        continue
    }
    # a plaintext key line inside a known block
    if ($line -match '^(\s+api-key:\s*)(sk-\S+)\s*$') {
        $prefix  = $Matches[1]
        $envName = $blockEnv[$currentBlock]
        if ($envName -and -not $keyOf.ContainsKey($envName)) {
            $keyOf[$envName]   = $Matches[2]
            $blockOf[$envName] = $currentBlock
            $out.Add($prefix + '${' + $envName + ':}')
            continue
        }
    }
    $out.Add($line)
}

if ($keyOf.Count -eq 0) {
    Write-Host 'No plaintext "sk-..." api-key found in application.yml. Nothing was changed.' -ForegroundColor Yellow
    exit 0
}

# --- 1. backup OUTSIDE the repo ---------------------------------------------
$stamp  = Get-Date -Format 'yyyyMMdd-HHmmss'
$backup = Join-Path $env:TEMP ("application.yml.{0}.bak" -f $stamp)
Copy-Item -LiteralPath $ymlPath -Destination $backup -Force

# --- 2. make sure spring.profiles.active=local is present --------------------
$springIdx = -1
for ($i = 0; $i -lt $out.Count; $i++) {
    if ($out[$i] -match '^spring:\s*$') { $springIdx = $i; break }
}

if ($springIdx -ge 0) {
    $profilesIdx = -1
    for ($i = $springIdx + 1; $i -lt $out.Count; $i++) {
        if ($out[$i] -match '^[A-Za-z0-9_\-]+:') { break }        # next top-level block
        if ($out[$i] -match '^\s+profiles:\s*$') { $profilesIdx = $i; break }
    }
    if ($profilesIdx -ge 0) {
        $activeExists = $false
        for ($i = $profilesIdx + 1; $i -lt $out.Count; $i++) {
            if ($out[$i] -match '^\s{0,2}[A-Za-z0-9_\-]+:') { break }
            if ($out[$i] -match '^\s+active:\s*\S') { $activeExists = $true; break }
        }
        if (-not $activeExists) { $out.Insert($profilesIdx + 1, '    active: local') }
        else { Write-Host 'NOTE: spring.profiles.active already set - please make sure it includes "local".' -ForegroundColor Yellow }
    }
    else {
        $out.Insert($springIdx + 1, '  profiles:')
        $out.Insert($springIdx + 2, '    active: local')
    }
}
else {
    $out.Add('')
    $out.Add('spring:')
    $out.Add('  profiles:')
    $out.Add('    active: local')
}

# --- 3. write application.yml back ------------------------------------------
[System.IO.File]::WriteAllLines($ymlPath, $out, $utf8NoBom)

# --- 4. build application-local.yml -----------------------------------------
$localOut = New-Object 'System.Collections.Generic.List[string]'
$localOut.Add('# ============================================================')
$localOut.Add('# LOCAL PRIVATE CONFIG - DO NOT COMMIT')
$localOut.Add('# Generated by migrate-secrets.ps1 at ' + (Get-Date -Format 'yyyy-MM-dd HH:mm'))
$localOut.Add('# Loaded because application.yml sets spring.profiles.active=local')
$localOut.Add('# Listed in .gitignore. Contains real API keys.')
$localOut.Add('# ============================================================')
$localOut.Add('')
foreach ($envName in ($blockOf.Keys | Sort-Object)) {
    $localOut.Add($blockOf[$envName] + ':')
    $localOut.Add('  api-key: ' + $keyOf[$envName])
    $localOut.Add('')
}
[System.IO.File]::WriteAllLines($localPath, $localOut, $utf8NoBom)

# --- 5. summary (no key contents) -------------------------------------------
Write-Host ''
Write-Host 'Done.' -ForegroundColor Green
Write-Host ('  backup of original application.yml : ' + $backup)
Write-Host ('  created                           : ' + $localPath)
foreach ($envName in ($blockOf.Keys | Sort-Object)) {
    Write-Host ('  ' + $blockOf[$envName] + '.api-key  ->  ${' + $envName + ':}   (real key moved to application-local.yml)')
}
Write-Host ''
Write-Host 'Verify with:  grep -rn "sk-" src/ --include=*.yml' -ForegroundColor Cyan
Write-Host 'Expected: only src/main/resources/application-local.yml matches.' -ForegroundColor Cyan
